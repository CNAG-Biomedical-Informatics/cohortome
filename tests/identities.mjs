import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const source = readFileSync(new URL('../static/js/identities.js', import.meta.url), 'utf8');
const { decodeIdentity, displayIdentity } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const key = 'cohortome-v1-' + Buffer.from(JSON.stringify(['étude', 'sample', '雪:01'])).toString('base64url');
assert.deepEqual(decodeIdentity(key), { datasetId: 'étude', kind: 'sample', sourceId: '雪:01' });
assert.equal(displayIdentity(key), 'étude · 雪:01');
assert.equal(displayIdentity(key, false), '雪:01');
assert.equal(displayIdentity('C2_' + key), 'C2_étude · 雪:01');
assert.equal(displayIdentity('SYN0001'), 'SYN0001');
assert.equal(decodeIdentity('cohortome-v1-bad'), null);
console.log('Dataset identity labels passed.');
