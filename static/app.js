      function nowIso() {
        return new Date().toISOString();
      }

      function shortTimestamp(value) {
        if (!value) {
          return "Just now";
        }
        const parsed = new Date(value);
        if (Number.isNaN(parsed.getTime())) {
          return "Just now";
        }
        return parsed.toLocaleString([], {
          month: "short",
          day: "numeric",
          hour: "2-digit",
          minute: "2-digit",
        });
      }

